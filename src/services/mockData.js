// Helper to generate past dates (YYYY-MM-DD)
const getPastDateStr = (daysAgo) => {
  const d = new Date();
  d.setDate(d.getDate() - daysAgo);
  return d.toISOString().split('T')[0];
};

// Generate realistic 30-day attendance history across all batches
const generateSeedAttendance = () => {
  const records = [];
  const students = MOCK_USERS.filter(u => u.role === 'student');
  let idCounter = 1000;

  const sessionDaysAgo = [0, 2, 4, 7, 9, 11, 14, 16, 18, 21, 23, 25, 27, 28, 29];

  sessionDaysAgo.forEach(daysAgo => {
    const dateStr = getPastDateStr(daysAgo);

    students.forEach(student => {
      const charSum = student.id.split('').reduce((acc, c) => acc + c.charCodeAt(0), 0);
      const isAbsent = (charSum + daysAgo) % 7 === 0;

      records.push({
        id: `att_${idCounter++}`,
        studentId: student.id,
        batchId: student.batchId,
        date: dateStr,
        status: isAbsent ? 'absent' : 'present',
        markedBy: 'usr_admin_1',
        markedByName: 'Aarav Sharma (Admin)',
        createdAt: new Date(Date.now() - daysAgo * 86400000).toISOString(),
        updatedAt: new Date(Date.now() - daysAgo * 86400000).toISOString()
      });
    });
  });

  return records;
};

